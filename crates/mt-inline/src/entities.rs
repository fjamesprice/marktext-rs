//! The HTML5 named character references — the table `getAttributes` decodes
//! attribute values against.
//!
//! # Why this is here, and why it is not [`crate::escape`]
//!
//! Two entity tables live in this crate and they are **not** the same table.
//!
//! - [`crate::escape`] holds `config/escapeCharacter.ts` — marktext's own list
//!   of 269 entity strings, which *is* the `html_escape` rule (`rules.ts:45`
//!   builds the regex by joining it). It is a markdown-level construct: it
//!   decides which `&…;` sequences become their own token.
//! - This is the **HTML5** table, all 2125 names, and it belongs to
//!   [`crate::html`]. `getAttributes` runs the whole match through a
//!   `DOMParser`, so an attribute value has its character references resolved
//!   by the *HTML* parser before it ever reaches the token — `<a
//!   href="&ouml;&ouml;.html">` gives `href` the value `öö.html`, and
//!   `&ouml;` is not in marktext's list.
//!
//! Using `escape.rs` here would be wrong in a way that is hard to see: it is a
//! *rule alternation* rather than a decode map, so it is ordered and its 269
//! entries hold only 252 distinct keys — and, more to the point, it is
//! **marktext's** list of what markdown treats as an entity, which is neither a
//! subset nor a superset of HTML5's.
//!
//! *Corrected at S6, which is the stage that actually built the decode
//! direction.* This paragraph used to add that the repeated keys are "mapped to
//! different characters at different indices". They are not — every repeat
//! pairs with the same character, measured against the running module. The
//! claim was decoration on an argument that never needed it; see
//! [`crate::escape`]'s header for the enumeration.
//!
//! # Provenance
//!
//! Generated at M1 S4 from the WHATWG named-character-reference list, and
//! **verified entry by entry against the engine that actually runs**:
//! happy-dom's `XMLEncodeUtility.decodeHTMLAttributeValue` delegates to
//! `entities`' `decodeHTMLAttribute`, and every one of the 2125 names was put
//! through it and compared. Zero mismatches. That check is what makes this a
//! measurement rather than a transcription — the same standard §3 rule 3 sets
//! for the character classes in [`crate::rules`].
//!
//! # The third field
//!
//! `true` when the name also has a **semicolon-less** legacy form, which is
//! 106 of the 2125 — `&amp` decodes, `&notin` does not. HTML5 keeps those for
//! compatibility and they are exactly the ones that make the attribute-value
//! rule observable: a semicolon-less match followed by `=` or an ASCII
//! alphanumeric is left literal, which is why `&notit;` stays `&notit;` while
//! `&not;` becomes `¬`. [`crate::html::decode_attribute_value`] is where that
//! rule lives.
//!
//! Sorted by name in byte order, so the lookup is a binary search. Names are
//! ASCII alphanumeric throughout, and the longest is 31 bytes
//! (`CounterClockwiseContourIntegral`), which bounds the longest-match walk.

